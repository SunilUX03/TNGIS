import type { LayerCategory, LayerLeaf } from "../types";

function leaf(name: string, hasData = false, dataRef?: LayerLeaf["dataRef"]): LayerLeaf {
  const id = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  return { id, name, hasData, dataRef };
}

